/**
 * Writes src/cms/active-content.ts from scripts/seed-documents.mjs.
 * If Firestore is readable, remote content documents replace the seed copies.
 * A failed or denied read keeps the seed, so builds work before the first seed.
 */
import 'dotenv/config'
import { writeFileSync } from 'node:fs'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildDocuments } from './seed-documents.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const images = JSON.parse(readFileSync(join(root, 'scripts/seed-images.json'), 'utf8'))
const seed = buildDocuments(images).filter((doc) => doc._type !== 'adminCredentials')

function decodeField(field) {
  if (!field || typeof field !== 'object') return null
  if ('stringValue' in field) return field.stringValue
  if ('booleanValue' in field) return field.booleanValue
  if ('integerValue' in field) return Number(field.integerValue)
  if ('doubleValue' in field) return field.doubleValue
  if ('nullValue' in field) return null
  if ('timestampValue' in field) return field.timestampValue
  if ('arrayValue' in field) return (field.arrayValue.values || []).map(decodeField)
  if ('mapValue' in field) return decodeFields(field.mapValue.fields || {})
  return null
}

function decodeFields(fields) {
  const output = {}
  for (const [key, value] of Object.entries(fields)) output[key] = decodeField(value)
  return output
}

async function fetchRemoteContent() {
  const projectId = process.env.VITE_FIREBASE_PROJECT_ID || 'tejaswini-industries-32349'
  const apiKey = process.env.VITE_FIREBASE_API_KEY || ''
  const emulator = process.env.FIRESTORE_EMULATOR_HOST
  if (!emulator && !apiKey) return null

  const documents = []
  let pageToken = ''
  do {
    const url = emulator
      ? `http://${emulator}/v1/projects/${projectId}/databases/(default)/documents/content?pageSize=300${pageToken ? `&pageToken=${pageToken}` : ''}`
      : `https://firestore.googleapis.com/v1/projects/${projectId}/databases/(default)/documents/content?pageSize=300&key=${apiKey}${pageToken ? `&pageToken=${pageToken}` : ''}`
    const response = await fetch(url)
    if (!response.ok) {
      console.warn(`[build-content] Firestore read returned ${response.status}. Using seed content.`)
      return null
    }
    const body = await response.json()
    for (const entry of body.documents || []) {
      const decoded = decodeFields(entry.fields || {})
      const id = String(entry.name || '').split('/').pop()
      documents.push({ ...decoded, _id: decoded._id || id })
    }
    pageToken = body.nextPageToken || ''
  } while (pageToken)

  return documents
}

const remote = await fetchRemoteContent().catch((error) => {
  console.warn('[build-content] Firestore read failed. Using seed content.', error.message)
  return null
})

const merged = new Map(seed.map((doc) => [doc._id, doc]))
if (remote?.length) {
  for (const doc of remote) {
    if (doc._type === 'siteInquiry') continue
    merged.set(doc._id, doc)
  }
  console.log(`[build-content] Merged ${remote.length} Firestore content documents over seed.`)
} else {
  console.log(`[build-content] Using ${seed.length} seed documents.`)
}

const docs = [...merged.values()]
const output = `import type { CmsDoc } from './types'

/** Generated by scripts/build-content.mjs. Do not edit by hand. */
export const contentDocuments: CmsDoc[] = ${JSON.stringify(docs, null, 2)}
`
writeFileSync(join(root, 'src/cms/active-content.ts'), output)
console.log(`[build-content] Wrote ${docs.length} documents.`)
